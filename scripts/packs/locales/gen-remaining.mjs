function writeLocale(name, data) {
  const keys = Object.keys(bnPack);
  const missing = keys.filter((k) => !data[k]);
  if (missing.length) throw new Error(`${name} missing ${missing.length}: ${missing.join(", ")}`);
  const lines = [
    `/** ${name.toUpperCase()} base UI pack — 186 semantic keys (187–225 in tail-supplement.json). */`,
    `export const ${name}186 = {`,
  ];
  for (const key of keys) lines.push(`  ${key}: ${JSON.stringify(data[key])},`);
  lines.push("};");
  lines.push("");
  fs.writeFileSync(path.join(__dirname, `${name}186.mjs`), lines.join("\n"));
  console.log(`${name}186.mjs: ${keys.length} keys`);
}

